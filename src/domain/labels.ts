// 項目キー (docs/design.md §4.1) → 標準の表示名。項目名の差し替え (labelOverrides) の標準で、検証器の科目名の規則 (label-spelling・account-section) が使う。
// 画面の Task (#27) が表示名の出所として使う。セグメントの行の見出しは会社の設定 (Company.segmentNames) で、ここは列の名前。
import type { DocKind } from './types';

/** path から項目キーを作る: 期・予実の段 (previous・current・forecast・actual) と、末尾の changeRate・amount を取り除き、資料の種類を頭に付ける。 */
export function itemKey(doc: DocKind, path: string): string {
  const segments = path.split('.').filter((s) => !['previous', 'current', 'forecast', 'actual'].includes(s));
  const last = segments[segments.length - 1];
  if (last === 'changeRate' || last === 'amount') segments.pop();
  return [doc, ...segments].join('.');
}

