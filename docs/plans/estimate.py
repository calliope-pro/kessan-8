PLANS = {'A': A, 'B': B, 'C': C}


def schedule(tasks, scale_content=1.0, scale_gen=1.0):
    T = {}
    for i, (lab, st, h, deps, kind) in tasks.items():
        f = scale_content if kind == 'c' else scale_gen if kind == 'g' else 1.0
        T[i] = dict(lab=lab, story=st, h=h * K * f, deps=deps, kind=kind)
    ES, EF = {}, {}

    def go(i):
        if i in EF:
            return EF[i]
        ES[i] = max([go(d) for d in T[i]['deps']], default=0.0)
        EF[i] = ES[i] + T[i]['h']
        return EF[i]

    for i in T:
        go(i)
    cp = max(EF.values())
    end = max(EF, key=EF.get)
    path = [end]
    while T[path[-1]]['deps']:
        path.append(max(T[path[-1]]['deps'], key=lambda x: EF[x]))
    path.reverse()
    pts = sorted(set(list(ES.values()) + list(EF.values())))
    width = max(sum(1 for i in T if ES[i] <= (a + b) / 2 < EF[i]) for a, b in zip(pts, pts[1:]))
    return dict(T=T, ES=ES, EF=EF, cp=cp, path=path, total=sum(t['h'] for t in T.values()), width=width)


