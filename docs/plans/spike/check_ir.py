"""試作 (#14): hand-q01-ir.json が hand-q01-full.json (短信) と整合するか、異変の版が想定した 1 点だけ食い違うかを確かめる。
標準ライブラリのみ。使いかた (docs/plans/spike/ で): python3 check_ir.py
四捨五入は 0.5 を遠い側へ (作成要領の端数処理。% は小数第一位未満を四捨五入)。製品のコードではない。
"""
import copy
import json
from fractions import Fraction


def rh(n, d=1):
    f = Fraction(n) / d
    return int((f * 2 + (1 if f >= 0 else -1)) // 2) if f >= 0 else -int((-f * 2 + 1) // 2)


def pct(n, d):
    return rh(n * 1000, d) / 10


def checks(ir, q):
    s, pl, bs, cf = ir["スライド"], q["損益計算書"], q["貸借対照表"], q["キャッシュ・フロー計算書"]
    sm, seg = q["サマリー"], q["注記"]["セグメント情報"]
    p0, p1 = pl["前期"], pl["当期"]
    R = []
    add = lambda name, ok: R.append((name, bool(ok)))
    h = s["1 ハイライト"]
    for k, key in (("売上高", "売上高"), ("営業利益", "営業利益"), ("経常利益", "経常利益"), ("親会社株主に帰属する当期純利益", "親会社株主に帰属する当期純利益")):
        add(f"短信-1 {k}の金額", h[k]["金額"] == p1[key])
        add(f"1 {k}の前期比", h[k]["前期比(%)"] == pct(p1[key] - p0[key], p0[key]))
    add("短信-1 年間配当金", h["年間配当金(円)"] == sm["年間配当金(円)"])
    add("短信-1 配当性向", h["配当性向(%)"] == sm["配当性向(%)"])
    g = s["2 業績"]
    for k in ("売上高", "売上総利益", "営業利益"):
        add(f"短信-2 {k}", g[k]["前期"] == p0[k] and g[k]["当期"] == p1[k])
    add("2 売上総利益率", g["売上総利益率(%)"]["前期"] == pct(p0["売上総利益"], p0["売上高"]) and g["売上総利益率(%)"]["当期"] == pct(p1["売上総利益"], p1["売上高"]))
    add("2 営業利益率", g["営業利益率(%)"]["前期"] == pct(p0["営業利益"], p0["売上高"]) and g["営業利益率(%)"]["当期"] == pct(p1["営業利益"], p1["売上高"]))
    t = s["3 セグメント"]
    for name in ("電機部品事業", "産業機器事業"):
        for item, key in (("売上高", "売上高"), ("利益", "利益")):
            v = t[name][item]
            add(f"短信-3 {name}の{item}", v["前期"] == seg["前期"][name][key] and v["当期"] == seg["当期"][name][key])
            add(f"3 {name}の{item}の前期比", v["前期比(%)"] == pct(v["当期"] - v["前期"], v["前期"]))
        add(f"3 {name}の売上構成比", t[name]["売上構成比(%)"] == pct(t[name]["売上高"]["当期"], p1["売上高"]))
    add("3 セグメント利益 + 調整額 = 連結の営業利益 (当期・前期)", all(
        t["電機部品事業"]["利益"][c] + t["産業機器事業"]["利益"][c] + t["調整額(全社費用)"][c] == t["連結の営業利益"][c] == p[k]
        for c, p, k in (("当期", p1, "営業利益"), ("前期", p0, "営業利益"))))
    f = s["4 見通し"]
    n, a = f["次期の予想"], f["当期の実績(比較用)"]
    add("短信-4 当期の実績 (売上高・営業利益)", a["売上高"] == p1["売上高"] and a["営業利益"] == p1["営業利益"])
    add("短信-4 当期の実績 (設備投資・減価償却費)", a["設備投資"] == -cf["有形固定資産の取得による支出"] and a["減価償却費"] == cf["減価償却費"])
    add("4 売上高の前期比", n["売上高前期比(%)"] == pct(n["売上高"] - a["売上高"], a["売上高"]))
    add("4 営業利益の前期比", n["営業利益前期比(%)"] == pct(n["営業利益"] - a["営業利益"], a["営業利益"]))
    u = s["5 補足"]
    add("短信-5 設備投資", u["設備投資"]["当期"] == -cf["有形固定資産の取得による支出"])
    add("短信-5 減価償却費", u["減価償却費"]["当期"] == cf["減価償却費"])
    b0, b1 = bs["前期末"], bs["当期末"]
    add("短信-5 有利子負債", u["有利子負債(短期借入金 + 長期借入金)"]["前期末"] == b0["短期借入金"] + b0["長期借入金"] and u["有利子負債(短期借入金 + 長期借入金)"]["当期末"] == b1["短期借入金"] + b1["長期借入金"])
    add("短信-5 現金及び預金", u["現金及び預金"]["前期末"] == b0["現金及び預金"] and u["現金及び預金"]["当期末"] == b1["現金及び預金"])
    add("5 純有利子負債 = 有利子負債 − 現金", all(u["純有利子負債"][c] == u["有利子負債(短期借入金 + 長期借入金)"][c] - u["現金及び預金"][c] for c in ("前期末", "当期末")))
    add("短信-5 自己資本比率", u["自己資本比率(%)"] == sm["自己資本比率(%)"])
    return R


if __name__ == "__main__":
    q = json.load(open("hand-q01-full.json"))
    ir = json.load(open("hand-q01-ir.json"))
    R = checks(ir, q)
    print(f"正常: {sum(ok for _, ok in R)}/{len(R)} 規則を通った。落ちた: {[n for n, ok in R if not ok]}")
    an = copy.deepcopy(ir)
    an["スライド"]["5 補足"]["設備投資"]["当期"] = 580
    R2 = checks(an, q)
    print(f"異変 (IR スライド 5 の設備投資 850 → 580): 落ちた規則 {[n for n, ok in R2 if not ok]}")
