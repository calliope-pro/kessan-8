"""試作 (#10): 生成した正常データが、会計の整合を満たすかを検証する。標準ライブラリのみ。製品のコードではない。

gen.py の内部を参照しない。dict (表示される値) だけを読み、表示値から再計算して確かめる。
規則は 2 種類: 整合 (hard。会計の等式・損益の連鎖・CF の連動・比率の再計算) と、
もっともらしさ (soft。遊び手に「正常」と見えるための範囲)。
"""
from fractions import Fraction


def rh(num, den=1):
    f = Fraction(num) / den
    n = f.numerator * 2 + (f.denominator if f >= 0 else -f.denominator)
    return int(n // (2 * f.denominator)) if f >= 0 else -int((-n) // (2 * f.denominator))


def tenths(x):  # 表示された % (小数 1 位) を整数に
    return None if x is None else round(x * 10)


def hund(x):
    return None if x is None else round(x * 100)


def hard_rules(d):
    """[(規則 ID, 通ったか)] を返す。"""
    b0, b1 = d["BS"]["前期末"], d["BS"]["当期末"]
    p0, p1 = d["PL"]["前期"], d["PL"]["当期"]
    cf, sm, sh = d["CF"], d["サマリー"], d["期中平均株式数(千株)"]
    R = []
    add = lambda rid, ok: R.append((rid, bool(ok)))

    for tag, b in (("前", b0), ("当", b1)):
        add(f"BS{tag}-流動資産", b["流動資産合計"] == b["現金及び預金"] + b["売掛金"] + b["棚卸資産"] + b["その他流動資産"])
        add(f"BS{tag}-固定資産", b["固定資産合計"] == b["有形固定資産"] + b["投資その他の資産"])
        add(f"BS{tag}-資産合計", b["資産合計"] == b["流動資産合計"] + b["固定資産合計"])
        add(f"BS{tag}-流動負債", b["流動負債合計"] == b["買掛金"] + b["短期借入金"] + b["未払法人税等"] + b["その他流動負債"])
        add(f"BS{tag}-負債合計", b["負債合計"] == b["流動負債合計"] + b["固定負債合計"])
        add(f"BS{tag}-株主資本", b["株主資本合計"] == b["資本金"] + b["資本剰余金"] + b["利益剰余金"])
        add(f"BS{tag}-純資産", b["純資産合計"] == b["株主資本合計"] + b["非支配株主持分"])
        add(f"BS{tag}-負債純資産", b["負債純資産合計"] == b["負債合計"] + b["純資産合計"])
        add(f"BS{tag}-貸借の等式", b["資産合計"] == b["負債純資産合計"])
    for tag, p in (("前", p0), ("当", p1)):
        add(f"PL{tag}-総利益", p["売上総利益"] == p["売上高"] - p["売上原価"])
        add(f"PL{tag}-営業利益", p["営業利益"] == p["売上総利益"] - p["販売費及び一般管理費"])
        add(f"PL{tag}-経常利益", p["経常利益"] == p["営業利益"] + p["営業外収益"] - p["営業外費用"])
        add(f"PL{tag}-税引前", p["税金等調整前当期純利益"] == p["経常利益"] + p["特別利益"] - p["特別損失"])
        add(f"PL{tag}-純利益", p["当期純利益"] == p["税金等調整前当期純利益"] - p["法人税等"])
        add(f"PL{tag}-親会社帰属", p["親会社株主に帰属する当期純利益"] == p["当期純利益"] - p["非支配株主に帰属する当期純利益"])

    # CF の内訳と合計
    sub = (cf["税金等調整前当期純利益"] + cf["減価償却費"] + cf["受取利息"] + cf["支払利息"] + cf["売上債権の増減額"]
           + cf["棚卸資産の増減額"] + cf["仕入債務の増減額"] + cf["その他資産の増減額"] + cf["その他負債の増減額"])
    add("CF-小計", cf["小計"] == sub)
    add("CF-営業", cf["営業活動によるキャッシュ・フロー"] == cf["小計"] + cf["利息の受取額"] + cf["利息の支払額"] + cf["法人税等の支払額"])
    add("CF-投資", cf["投資活動によるキャッシュ・フロー"] == cf["有形固定資産の取得による支出"] + cf["その他投資の増減額"])
    add("CF-財務", cf["財務活動によるキャッシュ・フロー"] == cf["短期借入金の増減額"] + cf["長期借入金の増減額"] + cf["配当金の支払額"])
    add("CF-増減", cf["現金及び現金同等物の増減額"] == cf["営業活動によるキャッシュ・フロー"] + cf["投資活動によるキャッシュ・フロー"]
        + cf["財務活動によるキャッシュ・フロー"] + cf["現金及び現金同等物に係る換算差額"])
    add("CF-期末", cf["現金及び現金同等物の期末残高"] == cf["現金及び現金同等物の期首残高"] + cf["現金及び現金同等物の増減額"])
    # CF の連動 (日本基準: 起点は税金等調整前当期純利益。資金の範囲 = 現金及び預金とする)
    add("連動-CF起点=PL税引前", cf["税金等調整前当期純利益"] == p1["税金等調整前当期純利益"])
    add("連動-CF期末=BS現金", cf["現金及び現金同等物の期末残高"] == b1["現金及び預金"])
    add("連動-CF期首=前期BS現金", cf["現金及び現金同等物の期首残高"] == b0["現金及び預金"])
    add("連動-売上債権増減", cf["売上債権の増減額"] == -(b1["売掛金"] - b0["売掛金"]))
    add("連動-棚卸資産増減", cf["棚卸資産の増減額"] == -(b1["棚卸資産"] - b0["棚卸資産"]))
    add("連動-仕入債務増減", cf["仕入債務の増減額"] == b1["買掛金"] - b0["買掛金"])
    add("連動-その他資産増減", cf["その他資産の増減額"] == -(b1["その他流動資産"] - b0["その他流動資産"]))
    add("連動-その他負債増減", cf["その他負債の増減額"] == b1["その他流動負債"] - b0["その他流動負債"])
    add("連動-法人税支払", -cf["法人税等の支払額"] == p1["法人税等"] - (b1["未払法人税等"] - b0["未払法人税等"]))
    add("連動-利息", cf["利息の受取額"] == -cf["受取利息"] == p1["営業外収益"] and cf["利息の支払額"] == -cf["支払利息"] == -p1["営業外費用"])
    add("連動-固定資産ロールフォワード", b1["有形固定資産"] == b0["有形固定資産"] - cf["有形固定資産の取得による支出"] - cf["減価償却費"])
    add("連動-その他投資", cf["その他投資の増減額"] == -(b1["投資その他の資産"] - b0["投資その他の資産"]))
    add("連動-借入", cf["短期借入金の増減額"] == b1["短期借入金"] - b0["短期借入金"]
        and cf["長期借入金の増減額"] == b1["長期借入金"] - b0["長期借入金"])
    add("連動-利益剰余金", b1["利益剰余金"] == b0["利益剰余金"] + p1["親会社株主に帰属する当期純利益"] + cf["配当金の支払額"])
    add("連動-非支配持分", b1["非支配株主持分"] == b0["非支配株主持分"] + p1["非支配株主に帰属する当期純利益"])
    add("連動-資本金等不変", b1["資本金"] == b0["資本金"] and b1["資本剰余金"] == b0["資本剰余金"])

    # 比率: 表示値から再計算 (四捨五入の規約は 0.5 を遠い側へ)
    def growth(cur, pre):
        return None if pre <= 0 else rh((cur - pre) * 1000, pre)

    parent, pp = p1["親会社株主に帰属する当期純利益"], p0["親会社株主に帰属する当期純利益"]
    eq0, eq1 = b0["純資産合計"] - b0["非支配株主持分"], b1["純資産合計"] - b1["非支配株主持分"]
    div = -cf["配当金の支払額"]
    add("表示-サマリーの値=財務諸表", sm["売上高"] == p1["売上高"] and sm["営業利益"] == p1["営業利益"] and sm["経常利益"] == p1["経常利益"]
        and sm["親会社株主に帰属する当期純利益"] == parent and sm["総資産"] == b1["資産合計"] and sm["純資産"] == b1["純資産合計"])
    # 表示値どうしを別の経路で突き合わせる (遊び手が検算したときに、正常が異変に見えないか)
    add("別経路-自己資本=純資産-非支配持分", sm["自己資本"] == sm["純資産"] - b1["非支配株主持分"])
    add("別経路-自己資本比率=自己資本/総資産", tenths(sm["自己資本比率"]) == rh(sm["自己資本"] * 1000, sm["総資産"]))
    eps = sm["1株当たり当期純利益"]
    add("別経路-EPS×株数=純利益", rh(hund(eps) * sh, 100000) == parent)
    add("別経路-BPS×株数=自己資本", rh(hund(sm["1株当たり純資産"]) * sh, 100000) == sm["自己資本"])
    add("別経路-配当性向=1株配当/EPS", sm["配当性向"] is None or eps <= 0
        or tenths(sm["配当性向"]) == rh(sm["年間配当金"] * 100 * 1000, hund(eps)))
    add("比率-売上高増減率", tenths(sm["売上高増減率"]) == rh((p1["売上高"] - p0["売上高"]) * 1000, p0["売上高"]))
    add("比率-営業利益増減率", tenths(sm["営業利益増減率"]) == growth(p1["営業利益"], p0["営業利益"]))
    add("比率-経常利益増減率", tenths(sm["経常利益増減率"]) == growth(p1["経常利益"], p0["経常利益"]))
    add("比率-純利益増減率", tenths(sm["親会社株主に帰属する当期純利益増減率"]) == growth(parent, pp))
    add("比率-EPS", hund(sm["1株当たり当期純利益"]) == rh(parent * 100000, sh))
    add("比率-自己資本比率", tenths(sm["自己資本比率"]) == rh(eq1 * 1000, b1["資産合計"]))
    add("比率-ROE", tenths(sm["自己資本当期純利益率"]) == rh(parent * 2000, eq0 + eq1))
    add("比率-BPS", hund(sm["1株当たり純資産"]) == rh(eq1 * 100000, sh))
    add("比率-配当性向", tenths(sm["配当性向"]) == (rh(div * 1000, parent) if parent > 0 else None))
    add("比率-配当金総額", div == rh(sm["年間配当金"] * sh, 1000))
    return R


def soft_rules(d):
    """もっともらしさ。遊び手に正常と見えるための範囲 (本試作の仮定。会計の分かる人の確認は未実施)。"""
    b0, b1 = d["BS"]["前期末"], d["BS"]["当期末"]
    p0, p1 = d["PL"]["前期"], d["PL"]["当期"]
    cf, sm = d["CF"], d["サマリー"]
    R = []
    add = lambda rid, ok: R.append((rid, bool(ok)))
    add("S-BS全項目が 0 以上", all(v >= 0 for b in (b0, b1) for k, v in b.items() if k != "利益剰余金"))
    add("S-流動比率 0.8〜4", 0.8 <= b1["流動資産合計"] / max(b1["流動負債合計"], 1) <= 4)
    add("S-自己資本比率 20〜80%", 20 <= sm["自己資本比率"] <= 80)
    add("S-営業利益率 -5〜25%", -5 <= p1["営業利益"] / p1["売上高"] * 100 <= 25)
    add("S-売上増減 ±20%", sm["売上高増減率"] is not None and abs(sm["売上高増減率"]) <= 20)
    add("S-営業利益あり", p1["営業利益"] > 0)
    add("S-実効税率 25〜40%", p1["税金等調整前当期純利益"] <= 0 or 25 <= p1["法人税等"] / p1["税金等調整前当期純利益"] * 100 <= 40)
    add("S-営業CF/営業利益 0.3〜3", p1["営業利益"] > 0 and 0.3 <= cf["営業活動によるキャッシュ・フロー"] / p1["営業利益"] <= 3)
    add("S-現金が売上の 3〜40%", 0.03 <= b1["現金及び預金"] / p1["売上高"] <= 0.40)
    add("S-配当性向 100% 以下", sm["配当性向"] is None or sm["配当性向"] <= 100)
    add("S-増減率が全部表示できる", all(sm[k] is not None for k in
        ("売上高増減率", "営業利益増減率", "経常利益増減率", "親会社株主に帰属する当期純利益増減率")))
    return R


def verify(d):
    h, s = hard_rules(d), soft_rules(d)
    return {"hard_fail": [r for r, ok in h if not ok], "soft_fail": [r for r, ok in s if not ok],
            "hard_n": len(h), "soft_n": len(s)}
